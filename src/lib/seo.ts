/**
 * Per-page metadata: title, description, canonical URL, and matching
 * Open Graph / Twitter tags. A page that sets its own openGraph replaces the
 * layout's, so the share image is listed here explicitly.
 */
export function pageMetadata({
  title,
  description,
  path
}: {
  title: string;
  description: string;
  path: string;
}): Metadata {
  const fullTitle = `${title} | ${SITE_NAME}`;
  return {
    title,
    description,
    alternates: { canonical: path },
    openGraph: {
      type: "website",
      siteName: SITE_NAME,
      locale: "en_US",
      url: path,
      title: fullTitle,
      description,
      images: [SHARE_IMAGE]
    },
    twitter: {
      card: "summary_large_image",
      title: fullTitle,
      description,
      images: [SHARE_IMAGE.url]
    }
  };
}
